"""Build bodies.js (block BODIES-BEGIN/END): Moon (Meeus ch. 47, from the ELP-2000/82 based table) and the planets
Venus, Mars, Jupiter, Saturn (VSOP87D heliocentric, truncated). Sources:
  VSOP87D.ven/.mar/.jup/.sat: IMCCE, ftp.imcce.fr/pub/ephem/planets/vsop87 (Bretagnon and Francou 1988)
  moonposition.go: Meeus, Astronomical Algorithms ch. 47 table as published in github.com/soniakeys/meeus (MIT)
usage: python3 gen_bodies.py <dir with the downloaded files> <engine.js> [threshold scale]
The block between BODIES-BEGIN and BODIES-END in engine.js is replaced (or added before the visual magnitudes)."""
import sys, re
src, out = sys.argv[1], sys.argv[2]; scale = float(sys.argv[3]) if len(sys.argv) > 3 else 6.0     # 6: every planet within 0.032' of DE440, 2000-2060
TAU = 0.061                                              # 61 years from J2000 in millennia: covers 2000-2060
# keep a term when amplitude * TAU**k >= threshold; thresholds (rad for L and B, AU for R) chosen so every planet stays under 1 arc-second
THR = {'ven': (2e-8, 2e-8, 2e-8), 'mar': (4e-8, 4e-8, 4e-8), 'jup': (1e-7, 1e-7, 2e-7), 'sat': (1e-7, 1e-7, 4e-7)}
def vsop(code):
    ser = {}; cur = None
    for line in open('%s/VSOP87D.%s' % (src, code)):
        if 'VSOP87' in line:
            m = re.search(r'VARIABLE (\d).*\*T\*\*(\d)', line); cur = (int(m.group(1)) - 1, int(m.group(2))); ser.setdefault(cur, []); continue
        f = line.split(); A, B, C = float(f[-3]), float(f[-2]), float(f[-1]); ser[cur].append((A, B, C))
    res = []
    for v in range(3):
        powers = []
        for k in range(6):
            terms = [t for t in ser.get((v, k), []) if abs(t[0]) * TAU ** k >= THR[code][v] * scale]
            powers.append(terms)
        while powers and not powers[-1]: powers.pop()
        res.append(powers)
    return res
def js_series(s):
    term = lambda t: '[%s,%s,%s]' % ('%.10g' % t[0], '%.6f' % t[1], '%.6f' % t[2])
    return '[' + ','.join('[' + ','.join('[' + ','.join(term(t) for t in p) + ']' for p in v) + ']' for v in s) + ']'
go = open('%s/moonposition.go' % src).read()
ta = re.findall(r'\{(-?\d+), (-?\d+), (-?\d+), (-?\d+), (-?\d+), (-?\d+)\}', go.split('var ta')[1].split('var tb')[0])
tb = re.findall(r'\{(-?\d+), (-?\d+), (-?\d+), (-?\d+), (-?\d+)\}', go.split('var tb')[1])
assert len(ta) == 60 and len(tb) == 60, (len(ta), len(tb))
n = 0
import io
o = io.StringIO()
if True:
    o.write('    /* BODIES-BEGIN (generated by gen_bodies.py, do not edit by hand) */\n')
    o.write('    /* Moon: Meeus ch. 47 [D, M, Mp, F, sum l (1e-6 deg), sum r (m)] and [D, M, Mp, F, sum b (1e-6 deg)] */\n')
    o.write('    var MOON_LR = [' + ','.join('[' + ','.join(t) + ']' for t in ta) + '],\n        MOON_B = [' + ','.join('[' + ','.join(t) + ']' for t in tb) + '];\n')
    o.write('    /* planets: VSOP87D (IMCCE), [L, B, R] each a list by power of tau of [A, B, C] terms, truncated to under 1 arc-second over 2000-2060 */\n')
    o.write('    var PLAN = {\n')
    names = [('ven', 'Venus'), ('mar', 'Mars'), ('jup', 'Jupiter'), ('sat', 'Saturn')]
    for i, (c, nm) in enumerate(names):
        s = vsop(c); n += sum(len(p) for v in s for p in v)
        o.write('      "%s": %s%s\n' % (nm, js_series(s), ',' if i < len(names) - 1 else ''))
    o.write('    };\n    /* BODIES-END */\n')
print('planet terms kept:', n)

blk = o.getvalue(); eng = open(out).read()
if '/* BODIES-BEGIN' in eng:
    i = eng.index('    /* BODIES-BEGIN'); j = eng.index('/* BODIES-END */\n', i) + len('/* BODIES-END */\n'); eng = eng[:i] + blk + eng[j:]
else:
    k = eng.index('    /* visual magnitudes'); eng = eng[:k] + blk + eng[k:]
open(out, 'w').write(eng)
